SEEKCOORD_MASK_DIR=${SEEKCOORD_MASK_DIR:-}
SEEKCOORD_IMAGE_DIR=${SEEKCOORD_IMAGE_DIR:-}
SEEKCOORD_FASTQ_ROOT=${SEEKCOORD_FASTQ_ROOT:-}
SEEKCOORD_RESULTS_ROOT=${SEEKCOORD_RESULTS_ROOT:-}
SEEKCOORD_SRC_DIR=${SEEKCOORD_SRC_DIR:-}
SEEKCOORD_BINSEGMENT_ROOT=${SEEKCOORD_BINSEGMENT_ROOT:-}
SEEKCOORD_ENV_NAME=${SEEKCOORD_ENV_NAME:-}
SEEKCOORD_ENV_PREFIX=${SEEKCOORD_ENV_PREFIX:-}
