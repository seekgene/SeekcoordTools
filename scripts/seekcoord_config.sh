#!/usr/bin/env bash

# Portable configuration loader for SeekcoordTools shell entrypoints.
# Source this file; do not execute it directly.

seekcoord_config_find_file() {
  if [[ -n "${SEEKCOORD_CONFIG:-}" ]]; then
    printf '%s\n' "$SEEKCOORD_CONFIG"
    return 0
  fi

  local repo_dir="${SEEKCOORD_REPO_DIR:-$(pwd)}"
  local candidates=(
    "${repo_dir}/seekcoord.local.env"
    "${repo_dir}/configs/seekcoord.env"
    "${HOME}/.config/seekcoord/seekcoord.env"
  )
  local candidate
  for candidate in "${candidates[@]}"; do
    if [[ -f "$candidate" ]]; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done
  return 1
}

seekcoord_config_set_defaults() {
  SEEKCOORD_WORKSPACE="${SEEKCOORD_WORKSPACE:-${HOME}/seekcoord}"
  SEEKCOORD_REFERENCE_DIR="${SEEKCOORD_REFERENCE_DIR:-${SEEKCOORD_WORKSPACE}/reference}"
  SEEKCOORD_FFPE_REFERENCE_DIR="${SEEKCOORD_FFPE_REFERENCE_DIR:-${SEEKCOORD_REFERENCE_DIR}/Homo_sapiens_wtpanel}"
  SEEKCOORD_MASK_DIR="${SEEKCOORD_MASK_DIR:-${SEEKCOORD_WORKSPACE}/ST_mask}"
  SEEKCOORD_IMAGE_DIR="${SEEKCOORD_IMAGE_DIR:-${SEEKCOORD_WORKSPACE}/images}"
  SEEKCOORD_FASTQ_ROOT="${SEEKCOORD_FASTQ_ROOT:-${SEEKCOORD_WORKSPACE}/fastq}"
  SEEKCOORD_RESULTS_ROOT="${SEEKCOORD_RESULTS_ROOT:-${SEEKCOORD_WORKSPACE}/results}"
  SEEKCOORD_SRC_DIR="${SEEKCOORD_SRC_DIR:-${SEEKCOORD_WORKSPACE}/src}"
  SEEKCOORD_BINSEGMENT_ROOT="${SEEKCOORD_BINSEGMENT_ROOT:-${SEEKCOORD_WORKSPACE}/binSegment}"

  SEEKCOORD_CONDA_ROOT="${SEEKCOORD_CONDA_ROOT:-}"
  SEEKCOORD_ENV_NAME="${SEEKCOORD_ENV_NAME:-seekcoord18}"
  SEEKCOORD_ENV_PREFIX="${SEEKCOORD_ENV_PREFIX:-}"
  SEEKCOORD_STAR_MULTIMAP="${SEEKCOORD_STAR_MULTIMAP:-}"
  SEEKCOORD_STARDIST_MODEL_DIR="${SEEKCOORD_STARDIST_MODEL_DIR:-}"
  SEEKCOORD_SPATIAL_REPORT_GENERATOR="${SEEKCOORD_SPATIAL_REPORT_GENERATOR:-}"
  SEEKCOORD_SCRNA_REPORT_GENERATOR="${SEEKCOORD_SCRNA_REPORT_GENERATOR:-}"

  if [[ -n "$SEEKCOORD_STARDIST_MODEL_DIR" && -z "${STARDIST_MODEL_DIR:-}" ]]; then
    export STARDIST_MODEL_DIR="$SEEKCOORD_STARDIST_MODEL_DIR"
  fi

  export SEEKCOORD_WORKSPACE SEEKCOORD_REFERENCE_DIR SEEKCOORD_FFPE_REFERENCE_DIR
  export SEEKCOORD_MASK_DIR SEEKCOORD_IMAGE_DIR
  export SEEKCOORD_FASTQ_ROOT SEEKCOORD_RESULTS_ROOT
  export SEEKCOORD_SRC_DIR SEEKCOORD_BINSEGMENT_ROOT
  export SEEKCOORD_CONDA_ROOT SEEKCOORD_ENV_NAME SEEKCOORD_ENV_PREFIX
  export SEEKCOORD_STAR_MULTIMAP
  export SEEKCOORD_STARDIST_MODEL_DIR SEEKCOORD_SPATIAL_REPORT_GENERATOR SEEKCOORD_SCRNA_REPORT_GENERATOR
}

seekcoord_config_load() {
  if [[ "${SEEKCOORD_CONFIG_LOADED:-0}" == "1" ]]; then
    return 0
  fi

  local config_file=""
  if config_file="$(seekcoord_config_find_file 2>/dev/null)"; then
    if [[ ! -f "$config_file" ]]; then
      echo "ERROR: SEEKCOORD_CONFIG points to a missing file: $config_file"
      exit 1
    fi
    # shellcheck source=/dev/null
    source "$config_file"
    SEEKCOORD_CONFIG_FILE="$config_file"
  else
    SEEKCOORD_CONFIG_FILE=""
  fi

  SEEKCOORD_CONFIG_LOADED=1
  export SEEKCOORD_CONFIG_LOADED SEEKCOORD_CONFIG_FILE
  seekcoord_config_set_defaults
}

